// Browser verification for the isolated /experience concept only.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { Browser, sleep } from "../.claude/skills/taste-skill/scripts/lib/cdp.mjs";

const base = process.env.EXPERIENCE_URL || "http://localhost:3000";
const out = resolve(process.env.EXPERIENCE_OUT || ".taste-skill/experience");
mkdirSync(out, { recursive: true });
const reveal = JSON.parse(readFileSync(resolve("public/experience/original-upscaled/manifest.json"), "utf8"));
const lastFrame = reveal.frames - 1;
const backdropSamples = JSON.parse(readFileSync(resolve("public/experience/original-upscaled/backdrops.json"), "utf8"));
const browser = await Browser.launch();
const page = await browser.newPage({ width: 1440, height: 1000 });
const results = [];
const check = (condition, name) => { results.push({ name, passed: !!condition }); if (!condition) throw Error(name); };
const capture = name => page.screenshot({ path: resolve(out, name + ".png"), format: "png" });
const waitFor = async (fn, arg) => { for (let i = 0; i < 80; i++) { if (await page.eval(fn, arg)) return; await sleep(250); } throw Error("Timed out waiting for hydration / animation"); };
try {
  await page.goto(base + "/experience", { timeoutMs: 60000, settleMs: 2000 });
  await waitFor(() => !!document.querySelector("canvas[data-frame]"));
  check(await page.eval(() => getComputedStyle(document.querySelector(".ax-sticky")).position === "sticky"), "Isolated stylesheet is applied");
  check(await page.eval(() => document.querySelector("h1").textContent.includes("Connected")), "Hero content present");
  check(await page.eval(() => document.documentElement.scrollWidth <= innerWidth + 1), "Desktop has no horizontal overflow");
  check(await page.eval(() => document.querySelector(".ax-poster").currentSrc.includes("original-upscaled/desktop/000.webp")), "Opening poster matches the uncropped first playback frame");
  check(await page.eval(() => Number(document.querySelector("canvas").dataset.frame) === 0), "Scroll scene starts at frame zero");
  check(await page.eval(() => !document.querySelector(".ax-sceneProgress") && !document.querySelector(".ax-scene").textContent.includes("/ 100")), "No numeric progress or loading-style display");
  check(await page.eval(() => document.querySelector(".ax-art").offsetWidth >= innerWidth * 0.99), "Video uses the full viewport width");
  check(await page.eval(() => document.querySelector(".ax-heroCopy").getBoundingClientRect().left < innerWidth * 0.1), "Opening typography is aligned left");
  check(await page.eval(expected => ["--edge-tl", "--edge-tr", "--edge-bl", "--edge-br"].every((name, i) => document.querySelector(".ax-heroModule").style.getPropertyValue(name) === expected[i]), backdropSamples[0]), "Opening backdrop matches the source frame edge samples");
  await capture("01-opening");
  await sleep(700);
  check(await page.eval(() => Number(document.querySelector("canvas").dataset.frame) === 0), "Video stays still without scrolling");
  const sceneDistance = await page.eval(() => document.querySelector(".ax-scene").offsetHeight - innerHeight);
  await page.wheel(Math.round(sceneDistance / 2));
  await sleep(1300);
  check(await page.eval(() => Number(document.querySelector("canvas").dataset.frame) > 20), "Scrolling advances video frames");
  await capture("02-mid-scroll");
  await page.wheel(Math.ceil(sceneDistance / 2));
  await sleep(1300);
  await waitFor(expected => Number(document.querySelector("canvas").dataset.frame) === expected, lastFrame);
  check(await page.eval(expected => Number(document.querySelector("canvas").dataset.frame) === expected, lastFrame), "Sector and map reveal reaches exact final frame");
  check(await page.eval(() => Number(document.querySelector("canvas").dataset.cache) <= 57), "Decoded frame cache is bounded");
  check(await page.eval(() => getComputedStyle(document.querySelector(".ax-heroCopy")).opacity === "0"), "Heading gives way to the expanded scene");
  check(await page.eval(expected => ["--edge-tl", "--edge-tr", "--edge-bl", "--edge-br"].every((name, i) => document.querySelector(".ax-heroModule").style.getPropertyValue(name) === expected[i]), backdropSamples[lastFrame]), "Ending backdrop follows the final frame edge samples");
  await capture("03-connected");
  await page.wheel(-Math.round(sceneDistance * 0.4));
  await sleep(1200);
  check(await page.eval(() => Number(document.querySelector("canvas").dataset.frame) < 130), "Scrolling backward reverses the reveal");
  await capture("03b-reverse-scroll");
  await page.eval(() => document.querySelector("#explore").scrollIntoView());
  await sleep(800);
  await page.eval(() => document.querySelector('[role="tabpanel"]').scrollIntoView({ block: "center" }));
  await sleep(900);
  await capture("04-document-workflow");
  await page.eval(() => document.querySelector('[role="tabpanel"] button').click());
  await sleep(2400);
  check(await page.eval(() => document.querySelector('[aria-live="polite"]').textContent.includes("Ready for your review")), "Document demo completes review");
  for (const index of [1, 2]) {
    await page.eval(i => document.querySelector(`#experience-tab-${i}`).click(), index);
    check(await page.eval(() => document.querySelector('[role="tabpanel"] button').textContent.includes("Start")), `Workflow ${index} resets review`);
    await page.eval(() => document.querySelector('[role="tabpanel"] button').click());
    await sleep(2300);
    check(await page.eval(() => document.querySelector('[aria-live="polite"]').textContent.includes("Ready for your review")), `Workflow ${index} demo completes`);
  }
  await capture("05-credit-workflow");
  await page.eval(() => document.querySelector("#approach").scrollIntoView());
  await sleep(900);
  await capture("06-approach");
  await page.setViewport({ width: 390, height: 844, mobile: true });
  await page.goto(base + "/experience", { timeoutMs: 45000, settleMs: 1500 });
  await waitFor(() => !!document.querySelector("canvas[data-frame]"));
  check(await page.eval(() => document.documentElement.scrollWidth <= innerWidth + 1), "Mobile has no horizontal overflow");
  check(await page.eval(() => document.querySelector(".ax-poster").currentSrc.includes("original-upscaled/mobile/000.webp")), "Mobile uses the smaller opening asset");
  await capture("07-mobile-opening");
  await page.wheel(1200);
  await sleep(1400);
  await waitFor(expected => Number(document.querySelector("canvas").dataset.frame) === expected, lastFrame);
  check(await page.eval(() => getComputedStyle(document.querySelector(".ax-sectorLegend")).opacity === "1"), "Mobile ending has readable sector labels");
  await capture("07b-mobile-ending");
  await page.eval(() => document.querySelector('[role="tabpanel"]').scrollIntoView());
  await sleep(900);
  await capture("08-mobile-workflow");
  check(await page.eval(() => document.querySelector('[role="tabpanel"]').getBoundingClientRect().width <= innerWidth), "Mobile workflow fits viewport");
  await page.send("Emulation.setEmulatedMedia", { features: [{ name: "prefers-reduced-motion", value: "reduce" }] });
  await page.goto(base + "/experience", { timeoutMs: 45000, settleMs: 1200 });
  check(await page.eval(() => getComputedStyle(document.querySelector("canvas")).display === "none"), "Reduced motion uses still artwork");
  check(await page.eval(() => document.querySelector(".ax-poster").currentSrc.includes("189.webp")), "Reduced motion displays the completed sector scene");
  check(await page.eval(() => document.querySelector("main section").getBoundingClientRect().height < innerHeight * 1.1), "Reduced motion removes long sticky scroll");
  await capture("09-reduced-motion");
  check(!page.consoleErrors.length, "No browser runtime errors");
} finally {
  writeFileSync(resolve(out, "results.json"), JSON.stringify({ results, errors: page.consoleErrors }, null, 2));
  console.log(JSON.stringify(results, null, 2));
  await browser.close();
}
